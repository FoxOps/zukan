"""Pokémon species names in every language, to name cards across languages.

Pokémon cards carry national Pokédex numbers (`dexId`) but no id shared between the
Japanese and the international releases. With the species names (`species_names.json`,
from PokeAPI, regenerated by `scripts/pokemon_species.py`), a card name made of species
names and plain suffixes can be written in every language: "ルギアV" -> "Lugia V",
"Lugia VSTAR" -> "ルギアVSTAR". Names with other words ("Team Rocket's Mewtwo",
"かがやくリザードン") are left alone: their translation is not a word-for-word one.
"""

import json
import re
from functools import cache
from pathlib import Path

_DATA = Path(__file__).with_name("species_names.json")
LATIN_LANGUAGES = {"en", "fr", "de", "it", "es", "pt"}
# Mechanics printed after the name, identical in every language.
_SUFFIXES = {
    "v", "vmax", "vstar", "v-union", "vunion", "ex", "gx", "break", "lv.x", "lv", "x", "y",
    "prime", "legend", "star", "☆", "δ", "◇", "tag", "team", "&",
}  # fmt: skip
_SEPARATORS = re.compile(r"[\s&\-–]+")
# Words before the species name in Asian languages, and the English form: regional forms,
# Mega Evolutions, Radiant / Shining / Dark Pokémon. Only the English name is derived for
# them (other languages put these words in other places).
_PREFIXES = [
    (("ガラル", "伽勒尔", "伽勒爾", "가라르"), "Galarian {}"),
    (("アローラ", "阿罗拉", "阿羅拉", "알로라"), "Alolan {}"),
    (("ヒスイ", "洗翠", "히스이"), "Hisuian {}"),
    (("パルデア", "帕底亚", "帕底亞", "팔데아"), "Paldean {}"),
    (("メガ", "超级", "超級", "메가"), "Mega {}"),
    (("かがやく", "光辉", "光輝", "빛나는"), "Radiant {}"),
    (("ひかる", "闪耀的", "閃耀的", "闪耀", "閃耀"), "Shining {}"),
    (("わるい", "坏坏", "壞壞"), "Dark {}"),
    (("いちげき", "一击", "一擊", "일격"), "Single Strike {}"),
    (("れんげき", "连击", "連擊", "연격"), "Rapid Strike {}"),
]
# Mega Evolution forms written against the suffix: "リザードンXex" = Charizard X ex.
_MEGA_FORM = re.compile(r"(?<=[^\sA-Za-z])([XY])(ex|EX)$")
_DELTA = re.compile(r"\s*[（(]デルタ種[）)]\s*$")
_ASIAN = {"ja", "ko", "zh-hans", "zh-hant"}


@cache
def species_names() -> dict[int, dict[str, str]]:
    raw = json.loads(_DATA.read_text())
    return {int(dex): names for dex, names in raw.items()}


def _name_in(lang: str, names: dict[str, str]) -> str | None:
    # Portuguese cards use the English names.
    return names.get(lang) or (names.get("en") if lang == "pt" else None)


def derive_names(name: str, lang: str, dex_ids: list[int]) -> dict[str, str]:
    """`name` (printed in `lang`) in the other languages, or {} when it is not only
    species names and suffixes. Asian names may also carry a form word ("ガラル",
    "メガ") or the delta species mark: only their English name is derived then."""
    if lang in _ASIAN:
        if not dex_ids:
            dex_ids = find_species(name, lang)
        english = _english_form(name, lang, dex_ids)
        if english:
            return {"en": english}
    return _derive(name, lang, dex_ids)


def _english_form(name: str, lang: str, dex_ids: list[int]) -> str | None:
    if _DELTA.search(name):
        rest = _DELTA.sub("", name)
        english = _derive(rest, lang, dex_ids).get("en") or _english_form(rest, lang, dex_ids)
        return f"{english} δ" if english else None
    stripped = name.strip()
    for words, form in _PREFIXES:
        for word in words:
            if stripped.startswith(word) and len(stripped) > len(word):
                rest = _MEGA_FORM.sub(r" \1 \2", stripped[len(word) :].strip())
                english = _derive(rest, lang, dex_ids).get("en")
                return form.format(english) if english else None
    return None


def _derive(name: str, lang: str, dex_ids: list[int]) -> dict[str, str]:
    known = species_names()
    species = [known.get(dex) for dex in dex_ids]
    if not species or any(s is None for s in species):
        return {}
    rest = name
    parts: list[tuple[int, str]] = []  # (position, species name in `lang`)
    for names in species:
        local = _name_in(lang, names)  # type: ignore[arg-type]
        position = rest.casefold().find(local.casefold()) if local else -1
        if local is None or position < 0:
            return {}
        parts.append((position, local))
        rest = rest[:position] + "\0" * len(local) + rest[position + len(local) :]
    leftover = [t for t in _SEPARATORS.split(rest.replace("\0", " ")) if t]
    if any(token.casefold() not in _SUFFIXES for token in leftover):
        return {}

    derived: dict[str, str] = {}
    targets = {lang for names in species for lang in names} | {"pt"}  # type: ignore[union-attr]
    for target in targets - {lang}:
        text = name
        for names in species:
            local, other = _name_in(lang, names), _name_in(target, names)  # type: ignore[arg-type]
            if other is None:
                break
            text = re.sub(re.escape(local), "\0" + other + "\0", text, count=1, flags=re.I)
        else:
            derived[target] = _spacing(text, target)
    return derived


def _spacing(text: str, lang: str) -> str:
    """Latin-script names put a space between the species and a suffix ("Lugia V"),
    Asian ones do not ("ルギアV")."""
    if lang in LATIN_LANGUAGES:
        text = re.sub(r"(?<=\w)\0(?=\w)", " ", text)
    else:
        text = re.sub(r"\0\s+(?=[A-Za-z☆δ◇])", "", text)
    return re.sub(r"\s+", " ", text.replace("\0", "")).strip()


@cache
def _by_name(lang: str) -> dict[str, int]:
    return {
        names[lang].casefold(): dex
        for dex, names in species_names().items()
        if names.get(lang) and len(names[lang]) > 1
    }


def find_species(name: str, lang: str) -> list[int]:
    """Pokédex number of the species whose name (in `lang`) the card name contains, the
    longest one ("太阳伊布ex" is Espeon, not Eevee); [] when none."""
    folded = name.casefold()
    found = [(len(local), dex) for local, dex in _by_name(lang).items() if local in folded]
    return [max(found)[1]] if found else []
